#!/usr/bin/env node
/*
 * Registers character images:  node tools/scan-images.js
 * Put one file per character in assets/characters/ named by its id
 * (png / webp / jpg / jpeg / svg). Characters without a file keep the built-in art.
 */
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'characters');
require(path.join(__dirname, '..', 'core', 'config.js'));
require(path.join(__dirname, '..', 'core', 'data.js'));
const D = globalThis.AMB.DATA;
const ids = [...Object.keys(D.HEROES), ...Object.keys(D.UNITS)];
const files = fs.readdirSync(dir);
const map = {}, unknown = [];
for (const f of files) {
  const m = f.match(/^(.+)\.(png|webp|jpe?g|svg)$/i);
  if (!m) continue;
  if (ids.includes(m[1])) map[m[1]] = 'assets/characters/' + f; else unknown.push(f);
}
fs.writeFileSync(path.join(dir, 'manifest.js'),
  "/* Generated by tools/scan-images.js — maps character id -> image file. Empty = built-in SVG art is used. */\n" +
  "globalThis.AMB = globalThis.AMB || {};\nAMB.IMAGES = " + JSON.stringify(map, null, 2) + ";\n");
console.log(`registered ${Object.keys(map).length}/${ids.length} images`);
console.log('missing:', ids.filter((i) => !map[i]).join(', ') || 'none');
if (unknown.length) console.log('ignored (name does not match a character id):', unknown.join(', '));
